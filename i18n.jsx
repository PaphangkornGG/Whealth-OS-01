const LangContext = React.createContext({ t: I18N.en, lang: 'en', setLang: () => {} });

function LangProvider({ children }) {
  const [lang, setLangState] = React.useState(() => {
    try { return localStorage.getItem('wealthos_lang') || 'en'; } catch { return 'en'; }
  });
  const setLang = React.useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem('wealthos_lang', l); } catch {}
  }, []);
  const value = React.useMemo(() => ({ t: I18N[lang], lang, setLang }), [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

// Hook
function useT() {
  return React.useContext(LangContext);
}

window.I18N = I18N;
window.LangContext = LangContext;
window.LangProvider = LangProvider;
window.useT = useT;
